"""Read-only dashboard: renders results/<exp_id>/items.json + summary.json
into a single self-contained HTML file (no JS deps, works offline).

Streamlit version planned for Phase 5 per docs/01 (O5); this static variant
exists so the demo has zero runtime dependencies.

Usage: python -m ragdx.app.dashboard [exp_id]
"""

from __future__ import annotations

import html
import json
import sys
from pathlib import Path

LABEL_COLORS = {
    "RETRIEVER": "#d93025", "GENERATOR": "#1a73e8", "INTERACTION": "#e37400",
    "NONE": "#188038", "QUESTION_ISSUE": "#9334e6", "ANOMALY": "#5f6368",
    "ABSTAIN": "#bdc1c6",
}


def _esc(x) -> str:
    return html.escape(str(x))


def render(exp_dir: str | Path) -> str:
    d = Path(exp_dir)
    items = json.loads((d / "items.json").read_text(encoding="utf-8"))
    summary = json.loads((d / "summary.json").read_text(encoding="utf-8"))
    manifest = json.loads((d / "manifest.json").read_text(encoding="utf-8"))

    dist = summary["attribution_distribution"]
    total = summary["n"] or 1
    bars = "".join(
        f'<div class="bar" style="width:{max(2.0, v/total*100)}%;background:{LABEL_COLORS.get(k,"#999")}">'
        f'<span>{_esc(k)}: {v} ({v/total*100:.0f}%)</span></div>'
        for k, v in sorted(dist.items(), key=lambda kv: -kv[1]))

    rows = []
    for it in items:
        lab = it["label"]
        cond = "".join(
            f'<td class="{"ok" if it[c]["em_loose"] else "bad"}">'
            f'{"✓" if it[c]["em_loose"] else "✗"}<div class="ans">{_esc(it[c]["text"])[:220]}</div></td>'
            for c in ("base", "gold", "retrieved"))
        rows.append(f"""<tr>
<td class="qid">{_esc(it['query_id'])}<div class="q">{_esc(it['question'])}</div>
    <div class="exp">expected: {_esc(it['answers'][0])}</div></td>
{cond}
<td><span class="label" style="background:{LABEL_COLORS.get(lab,'#999')}">{_esc(lab)}</span>
    <div class="ev">R@k={it['retrieved']['recall_at_k']:.2f}<br>{_esc(it['evidence'].get('reason',''))}</div></td>
</tr>""")

    acc = summary["accuracy"]
    mm = summary["mirage_metrics"]
    return f"""<!doctype html><html><head><meta charset="utf-8"><title>ragdx — {_esc(manifest['exp_id'])}</title>
<style>
body{{font:14px/1.5 system-ui,sans-serif;margin:2rem;color:#202124;background:#f8f9fa}}
h1{{font-size:20px}} table{{border-collapse:collapse;background:#fff;width:100%}}
th,td{{border:1px solid #dadce0;padding:8px;vertical-align:top;text-align:left}}
th{{background:#e8eaed;position:sticky;top:0}} .qid{{width:22%}} .q{{font-weight:600;margin-top:4px}}
.exp{{color:#5f6368;font-size:12px}} .ans{{color:#3c4043;font-size:12px;margin-top:4px}}
.ok{{background:#e6f4ea}} .bad{{background:#fce8e6}}
.label{{color:#fff;padding:2px 10px;border-radius:12px;font-size:12px;font-weight:600}}
.ev{{font-size:11px;color:#5f6368;margin-top:6px}}
.kpi{{display:inline-block;background:#fff;border:1px solid #dadce0;border-radius:8px;padding:10px 16px;margin:4px}}
.kpi b{{font-size:22px;display:block}}
.bar{{color:#fff;padding:4px 8px;border-radius:4px;margin:2px 0;font-size:12px}}
.meta{{color:#5f6368;font-size:12px;margin-top:8px}}
</style></head><body>
<h1>ragdx — {_esc(manifest['exp_id'])} · three-condition failure attribution</h1>
<div class="meta">model {_esc(manifest['model'])} · dataset {_esc(manifest['dataset'])} · n={manifest['n_items']} ·
{_esc(manifest['date'])} · git {_esc(manifest['git_hash'][:10])} · {_esc(manifest['duration_s'])}s ·
{manifest['total_tokens']} tokens · cache hits {manifest['cache_hits']}</div>
<div>
<span class="kpi"><b>{acc['base']:.0%}</b>base acc</span>
<span class="kpi"><b>{acc['gold']:.0%}</b>gold acc</span>
<span class="kpi"><b>{acc['retrieved']:.0%}</b>retrieved acc</span>
<span class="kpi"><b>{mm['nv']:.0%}</b>NV</span>
<span class="kpi"><b>{mm['ca']:.0%}</b>CA</span>
<span class="kpi"><b>{mm['ci']:.0%}</b>CI</span>
<span class="kpi"><b>{mm['cm']:.0%}</b>CM</span>
<span class="kpi"><b>{summary['mean_recall_at_k']:.2f}</b>mean R@k</span>
</div>
<h2 style="font-size:16px">Attribution distribution</h2>{bars}
<table><tr><th>question</th><th>base (no ctx)</th><th>gold ctx</th><th>retrieved ctx</th><th>attribution</th></tr>
{''.join(rows)}</table>
<p class="meta">generated by ragdx.app.dashboard (read-only over results/)</p>
</body></html>"""


def main() -> None:
    exp = sys.argv[1] if len(sys.argv) > 1 else "exp01"
    root = Path(__file__).resolve().parents[3]
    out = root / "results" / exp / "dashboard.html"
    out.write_text(render(root / "results" / exp), encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
